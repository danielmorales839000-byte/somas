import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';

test('owner objective, persisted Manager chat, actual runtime, browser agent, independent package, Root and mobile',async({page,request,browser})=>{
  await page.setViewportSize({width:1440,height:1000});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('Email',{exact:true}).fill('qa-owner@example.test');
  await page.getByLabel('Password',{exact:true}).fill('local-disposable-qa-password');
  await page.getByRole('button',{name:'Create free account'}).click();
  await expect(page.getByRole('heading',{name:'Application workspace'})).toBeVisible();
  await page.getByRole('button',{name:'+ New project'}).click();
  await page.getByLabel('Project name').fill('Northline Studio');
  await page.getByLabel('What should this application do?').fill('Showcase our furniture and accept customer inquiries. Build a polished catalog with verified customer workflows.');
  await page.getByRole('button',{name:'Provision instance'}).click();
  await expect(page.getByRole('heading',{name:'Your Manager',exact:true})).toBeVisible();
  await page.getByLabel('Message your Manager').fill('Change title to Northline Furniture');
  await page.getByRole('button',{name:'Send to Manager'}).click();
  await expect(page.locator('.chat-owner')).toContainText('Change title to Northline Furniture');
  await expect(page.locator('.chat-manager')).toHaveCount(1);
  await page.getByRole('button',{name:'Live organization',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Live organization'})).toBeVisible();
  await page.getByText('Mission execution controls',{exact:true}).click();
  await page.getByRole('button',{name:'Run bounded assessment'}).click();
  await expect(page.getByText('Deploy the application on an independent hostname',{exact:false})).toBeVisible();
  await expect(page.getByText('Application Package ↗',{exact:false})).toBeVisible();
  const agentResponse=await page.request.get('/api/projects');
  const currentProject=(await agentResponse.json()).projects[0];
  const team=await page.request.get(`/api/projects/${currentProject.id}/agents`);
  await expect(page.locator('.org-agent')).toHaveCount((await team.json()).agents.length);
  await page.locator('.org-agent').filter({hasText:'Developer'}).click();
  await expect(page.locator('.ops-inspector')).toContainText('isolated_coding_provider_not_configured');
  await page.locator('#toast').waitFor({state:'hidden'});
  await mkdir('docs/audit/ui',{recursive:true});
  await page.screenshot({path:'docs/audit/ui/organization-desktop.png',fullPage:true});
  // A refresh preserves messages; the customer site retains its own experience.
  await page.getByRole('button',{name:'Manager conversation',exact:true}).click();
  await page.screenshot({path:'docs/audit/ui/manager-conversation.png',fullPage:true});
  await page.reload();
  await page.getByRole('button',{name:/Northline Studio/}).click();
  await expect(page.locator('.chat-owner')).toContainText('Change title to Northline Furniture');
  const site=await page.getByRole('link',{name:'Open current site'}).getAttribute('href');
  const publicPage=await browser.newPage();await publicPage.goto(site);await expect(publicPage.locator('h1')).toHaveText('Northline Studio');await publicPage.close();
  // Run the actual scoped Playwright executor against this disposable backend.
  const projects=await page.request.get('/api/projects');const project=(await projects.json()).projects[0];
  const tokenResponse=await page.request.post(`/api/projects/${project.id}/operations/runner-token`,{headers:{'x-somas-request':'1',origin:'http://127.0.0.1:8788'},data:{}});
  expect(tokenResponse.status()).toBe(201);const {token}=await tokenResponse.json();
  const child=spawn(process.execPath,['scripts/run-browser-agent.mjs'],{env:{...process.env,SOMAS_BASE_URL:'http://127.0.0.1:8788',SOMAS_TARGET_ORIGIN:'http://127.0.0.1:8788',SOMAS_RUNNER_TOKEN:token,SOMAS_ALLOW_LOCAL_TEST:'true'},stdio:['ignore','pipe','pipe']});
  let output='';child.stdout.on('data',chunk=>output+=chunk);child.stderr.on('data',chunk=>output+=chunk);
  const code=await new Promise(r=>child.on('exit',r));expect(code,output).toBe(0);expect(output).toContain('"reported":true');
  await page.getByRole('button',{name:'Live organization',exact:true}).click();
  await page.getByRole('button',{name:'Refresh records'}).click();
  await expect(page.getByText('Browser Report ↗',{exact:false})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.screenshot({path:'docs/audit/ui/organization-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(392);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('link',{name:'Root control'}).click();
  await expect(page.getByRole('heading',{name:'Platform operations'})).toBeVisible();
  await expect(page.getByText('Northline Studio',{exact:true})).toHaveCount(0); // no customer mission/spec in Root metadata
  await page.screenshot({path:'docs/audit/ui/root-operations.png',fullPage:true});
  expect(errors).toEqual([]);
});
