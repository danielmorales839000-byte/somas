import {createRequire} from 'node:module';
import {writeFileSync,readFileSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
// Use the bundler already supplied by the pinned Vite version. No runtime
// filesystem, dynamic eval, credential or project data goes into this bundle.
export async function buildTeamSource(){
 const require=createRequire(import.meta.resolve('vite'));
 const {rolldown}=await import(pathToFileURL(require.resolve('rolldown')).href);
 const bundle=await rolldown({input:fileURLToPath(new URL('../lib/ai-team/worker.mjs',import.meta.url)),external:['cloudflare:workers']});
 const result=await bundle.generate({format:'esm',minify:true});await bundle.close();
 const output='// Generated by scripts/build-team-source.mjs. Edit lib/ai-team/ sources.\nexport default '+JSON.stringify(result.output[0].code)+';\n';
 const path=new URL('../lib/ai-team/bundle.generated.mjs',import.meta.url);
 let current='';try{current=readFileSync(path,'utf8')}catch{}if(current!==output)writeFileSync(path,output);
}
if(process.argv[1]===fileURLToPath(import.meta.url))await buildTeamSource();
